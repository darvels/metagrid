function applyHeadTranslations(dictionary) {
  document.title = dictionary["head.title"];

  const headBindings = [
    ["meta-description", "head.description"],
    ["og-title", "head.ogTitle"],
    ["og-description", "head.ogDescription"],
    ["twitter-title", "head.twitterTitle"],
    ["twitter-description", "head.twitterDescription"],
    ["og-image-alt", "hero.imageAlt"],
    ["twitter-image-alt", "hero.imageAlt"]
  ];

  headBindings.forEach(([id, key]) => {
    const element = document.getElementById(id);
    if (element && dictionary[key]) {
      element.setAttribute("content", dictionary[key]);
    }
  });
}

